"""Generate a single-outstanding AXI-Lite register bank and matching constants."""
import argparse
import re
from pathlib import Path
import yaml


def number(value):
    return int(str(value), 0)


def generate(source, verilog, c_dir, py_dir, tb_dir):
    # BaseLoader deliberately preserves the YAML key 'off' rather than treating it as False.
    contract = yaml.load(source.read_text(encoding='utf-8'), Loader=yaml.BaseLoader)
    name, regs = contract['name'], contract['regs']
    if not re.fullmatch('[a-z][a-z0-9_]*', name) or number(contract['width']) != 32:
        raise ValueError('Expected a named 32-bit register block')
    occupied = set()
    constants = {'BASE': number(contract['base'])}
    for reg in regs:
        reg['offset'] = number(reg['off'])
        reg['reset_value'] = number(reg.get('reset', '0'))
        if (not re.fullmatch('[A-Z][A-Z0-9_]*', reg['name']) or reg['offset'] % 4 or
                not 0 <= reg['offset'] <= 252 or reg['offset'] in occupied or
                not 0 <= reg['reset_value'] < 2**32 or reg.get('access', 'rw') not in ('ro', 'rw')):
            raise ValueError('Invalid/duplicate register contract')
        occupied.add(reg['offset'])
        constants[reg['name']] = reg['offset']
        field_mask = 0
        for field in reg.get('fields', []):
            positions = [int(x) for x in field['bits'].split(':')]
            hi, lo = positions[0], positions[-1]
            if len(positions) not in (1, 2) or not 0 <= lo <= hi < 32:
                raise ValueError('Invalid field bits')
            mask = ((1 << (hi-lo+1))-1) << lo
            if field_mask & mask or not re.fullmatch('[A-Z][A-Z0-9_]*', field['name']):
                raise ValueError('Invalid or overlapping field')
            field_mask |= mask
            constants[reg['name']+'_'+field['name']+'_SHIFT'] = lo
            constants[reg['name']+'_'+field['name']+'_MASK'] = mask
    ports = ['input wire aclk', 'input wire aresetn',
             'input wire [7:0] s_axi_awaddr', 'input wire s_axi_awvalid', 'output wire s_axi_awready',
             'input wire [31:0] s_axi_wdata', 'input wire [3:0] s_axi_wstrb',
             'input wire s_axi_wvalid', 'output wire s_axi_wready',
             'output reg s_axi_bvalid', 'input wire s_axi_bready', 'output wire [1:0] s_axi_bresp',
             'input wire [7:0] s_axi_araddr', 'input wire s_axi_arvalid', 'output wire s_axi_arready',
             'output reg [31:0] s_axi_rdata', 'output reg s_axi_rvalid',
             'input wire s_axi_rready', 'output wire [1:0] s_axi_rresp']
    rw = [r for r in regs if r.get('access', 'rw') == 'rw']
    ro = [r for r in regs if r.get('access') == 'ro' and 'reset' not in r]
    ports += ['output reg [31:0] reg_'+r['name'].lower() for r in rw]
    ports += ['input wire [31:0] ro_'+r['name'].lower() for r in ro]
    lines = ['// Generated by tools/regmap_codegen.py; do not edit.',
             'module '+name+'_regs (\n    '+',\n    '.join(ports)+'\n);',
             'reg aw_pending, w_pending;', 'reg [7:0] aw_address;',
             'reg [31:0] w_data;', 'reg [3:0] w_strobes;', 'integer lane;',
             'assign s_axi_awready=!aw_pending && !s_axi_bvalid;',
             'assign s_axi_wready=!w_pending && !s_axi_bvalid;',
             'assign s_axi_arready=!s_axi_rvalid;',
             "assign s_axi_bresp=2'b00; assign s_axi_rresp=2'b00;",
             'always @(posedge aclk) begin', 'if (!aresetn) begin',
             'aw_pending<=0; w_pending<=0; s_axi_bvalid<=0; s_axi_rvalid<=0; s_axi_rdata<=0;']
    lines += ['reg_%s<=32\'h%08x;' % (r['name'].lower(), r['reset_value']) for r in rw]
    lines += ['end else begin', 'if(s_axi_bvalid && s_axi_bready) s_axi_bvalid<=0;',
              'if(s_axi_awvalid && s_axi_awready) begin aw_pending<=1; aw_address<=s_axi_awaddr; end',
              'if(s_axi_wvalid && s_axi_wready) begin w_pending<=1; w_data<=s_axi_wdata; w_strobes<=s_axi_wstrb; end',
              'if(aw_pending && w_pending && !s_axi_bvalid) begin',
              'aw_pending<=0; w_pending<=0; s_axi_bvalid<=1;', 'case(aw_address)']
    for r in rw:
        lines += ["8'h%02x: for(lane=0;lane<4;lane=lane+1) if(w_strobes[lane]) reg_%s[lane*8+:8]<=w_data[lane*8+:8];" % (r['offset'], r['name'].lower())]
    lines += ['default: begin end', 'endcase', 'end',
              'if(s_axi_rvalid && s_axi_rready) s_axi_rvalid<=0;',
              'if(s_axi_arvalid && s_axi_arready) begin s_axi_rvalid<=1;', 'case(s_axi_araddr)']
    for r in regs:
        value = ('reg_'+r['name'].lower() if r in rw else
                 'ro_'+r['name'].lower() if r in ro else "32'h%08x" % r['reset_value'])
        lines += ["8'h%02x: s_axi_rdata<=%s;" % (r['offset'], value)]
    lines += ['default: s_axi_rdata<=0;', 'endcase', 'end', 'end', 'end', 'endmodule', '']
    for directory in (verilog, c_dir, py_dir, tb_dir):
        directory.mkdir(parents=True, exist_ok=True)
    (verilog/(name+'_regs.v')).write_bytes('\n'.join(lines).encode())
    prefix = name.upper()
    (c_dir/(name+'.h')).write_bytes(('#pragma once\n'+''.join(
        '#define %s_%s 0x%08xu\n' % (prefix, key, value) for key, value in constants.items())).encode())
    (py_dir/(name+'.py')).write_bytes(('"""Generated register offsets and masks."""\n'+''.join(
        '%s = 0x%x\n' % (key, value) for key, value in constants.items())).encode())
    (tb_dir/(name+'_defs.vh')).write_bytes(''.join(
        "localparam %s_%s = 32'h%08x;\n" % (prefix, key, value) for key, value in constants.items()).encode())
    print('REGMAP_GENERATION_PASS', name, len(regs))


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('source', type=Path)
    p.add_argument('--verilog', type=Path, required=True)
    p.add_argument('--c', type=Path, required=True)
    p.add_argument('--py', type=Path, required=True)
    p.add_argument('--tb', type=Path, required=True)
    a = p.parse_args()
    generate(a.source, a.verilog, a.c, a.py, a.tb)
