"""Extract board-specific PS7 settings from the read-only ATK HWH file."""

import argparse
import hashlib
from pathlib import Path
import re
import xml.etree.ElementTree as ET


KEEP = re.compile(
    r"^PCW_(UIPARAM_DDR_|PRESET_BANK|MIO_\d+_(IOTYPE|PULLUP|SLEW|DIRECTION)$|"
    r"(SD0|SD1|QSPI|ENET0|UART0|UART1|USB0)_|"
    r"SINGLE_QSPI|GPIO_MIO_GPIO_ENABLE|CRYSTAL_PERIPHERAL_FREQMHZ|"
    r"APU_PERIPHERAL_FREQMHZ|SDIO_PERIPHERAL_FREQMHZ|"
    r"QSPI_PERIPHERAL_FREQMHZ|ENET0_PERIPHERAL_FREQMHZ|EN_DDR)"
)
DROP = re.compile(
    r"ACT_|_DIVISOR|_CLKSRC|FREQMHZ_ACT|_HIGHADDR|_BASEADDR|_ISUSED|_INTR|_PCLK|_GRP_FBCLK|MIO_\d+_DIRECTION$"
)
EXPECTED = {
    "PCW_UIPARAM_DDR_PARTNO": "MT41J256M16 RE-125",
    "PCW_UIPARAM_DDR_BUS_WIDTH": "32 Bit",
    "PCW_UART0_UART0_IO": "MIO 14 .. 15",
    "PCW_ENET0_ENET0_IO": "MIO 16 .. 27",
    "PCW_SD0_SD0_IO": "MIO 40 .. 45",
    "PCW_SD1_SD1_IO": "MIO 46 .. 51",
    "PCW_USB0_USB0_IO": "MIO 28 .. 39",
    "PCW_PRESET_BANK1_VOLTAGE": "LVCMOS 1.8V",
}


def generate(source: Path, destination: Path) -> int:
    raw = source.read_bytes()
    root = ET.fromstring(raw)
    modules = [m for m in root.iter("MODULE") if m.get("MODTYPE") == "processing_system7"]
    if len(modules) != 1:
        raise ValueError(f"Expected one processing_system7 module, found {len(modules)}")
    params = {}
    for item in modules[0].iter("PARAMETER"):
        name, value = item.get("NAME", ""), item.get("VALUE", "")
        if KEEP.search(name) and not DROP.search(name) and value not in ("", "<Select>"):
            if any(character in value for character in "{}\\\r\n"):
                raise ValueError(f"Unsupported Tcl value for {name}: {value!r}")
            if name in params and params[name] != value:
                raise ValueError(f"Conflicting source values for {name}")
            params[name] = value
    for name, expected in EXPECTED.items():
        if params.get(name) != expected:
            raise ValueError(f"Board preset mismatch: {name}={params.get(name)!r}, expected {expected!r}")

    lines = [
        "# Generated by tools/gen_ps7_preset.py from ATK base.hwh; do not edit.",
        f"# Source SHA256: {hashlib.sha256(raw).hexdigest()}",
        "proc z20_apply_ps7_preset {ps7} {",
        "  set cfg [dict create]",
    ]
    lines.extend(f"  dict set cfg CONFIG.{name} {{{value}}}" for name, value in sorted(params.items()))
    lines += [
        "  # Bank voltage must precede MIO electrical values; validate the rest atomically.",
        "  foreach key {CONFIG.PCW_PRESET_BANK0_VOLTAGE CONFIG.PCW_PRESET_BANK1_VOLTAGE} {",
        "    if {[dict exists $cfg $key]} { set_property $key [dict get $cfg $key] [get_bd_cells $ps7] }",
        "  }",
        "  set_property -dict $cfg [get_bd_cells $ps7]",
        "}",
    ]
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return len(params)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("destination", type=Path)
    args = parser.parse_args()
    count = generate(args.source, args.destination)
    print(f"Generated {count} board parameters -> {args.destination}")
