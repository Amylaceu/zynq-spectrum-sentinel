"""Export integer uppercase Python parameters as an RTL include file."""
import argparse
import hashlib
import importlib.util
from pathlib import Path


def generate(source: Path, output: Path):
    spec = importlib.util.spec_from_file_location("sentinel_parameters", source)
    if spec is None or spec.loader is None:
        raise ValueError(f"Cannot import {source}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    values = {k: v for k, v in vars(module).items() if k.isupper() and type(v) is int}
    if not values:
        raise ValueError("No integer parameters found")
    lines = [
        "// Generated by tools/gen_params_vh.py; do not edit.",
        f"// Source SHA256: {hashlib.sha256(source.read_bytes()).hexdigest()}",
        "`ifndef SENTINEL_PARAMS_VH",
        "`define SENTINEL_PARAMS_VH",
    ]
    lines += [f"`define SP_{key} {value}" for key, value in sorted(values.items())]
    lines += ["`endif", ""]
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines), encoding="utf-8")
    print(f"Exported {len(values)} integer parameters -> {output}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    generate(args.source, args.output)
